/**
 * 「手动新建」与「Excel 导入」的区分基准（Stage 9.41 v2）
 *
 * ## 背景：用户两次反馈，最终口径
 *
 * ① 「我在职位管理新增了一个职位，在新增员工那里选不了」
 * ② 「新增了一个门店，也选不了」
 * ③ （我第一版改成「全部 ACTIVE 都能选」之后）
 *   > 「我说的是我手动新增的门店和职位，**之前那些已经不用的门店和职位就不用选了**」
 *
 * 所以候选范围 = **在用的 ∪ 手动新建的**，
 * 而**不是**「Excel 导入的 66 家门店 / 52 种职位全塞进去」。
 *
 * ## 怎么区分？靠 `createdAt` 的「日期」
 *
 * 两张表都有 `createdAt DateTime @default(now())`。实测分布：
 *   · **Excel 导入**：全部在 **2026-09-19**（13:43:25~13:43:30 之间，毫秒级逐条递增）
 *     门店 66 家、职位 52 种全在这一天
 *   · **用户手动新建**：都在 2026-09-19 **之后**
 *     职位 #323 `dd` = 2026-10-05；门店 #435 `dajdia店` = 2026-10-05、#434 `其他` = 2026-09-25
 *
 * ⚠️ **踩过的坑：不能用「晚于某个时刻」判**。
 *   导入的 52 种职位时间戳是 `13:43:25.496` `13:43:25.533` …**毫秒各不相同**，
 *   所以「晚于 `13:43:00`」会把它们全判成手动新建（实测 42 种历史职位全被误判）。
 *   → **必须用日期边界**（`YYYY-MM-DD` 字符串比较），不比较具体时刻。
 *
 * ⚠️ 为什么不用 `updatedAt`：合并门店时被改过（updatedAt 会刷新）→ 不能代表"诞生时间"。
 * ⚠️ 为什么不用绝对日期硬编码在两处：改代码时容易只改一处 → 统一从这里导出。
 */

/**
 * Excel 导入批次的日期（UTC）。
 *
 * 取导入当天（2026-09-19）。**当天及之前**的记录都算「导入的历史值」，
 * 之后的才算「用户手动新建」。
 *
 * ⚠️ 改这个值之前先跑一遍分布确认，别凭记忆改：
 *   `npx tsx -e "…prisma.position.groupBy({by:[{createdAt:{…}}]})"`
 */
export const IMPORT_BATCH_DATE = "2026-09-19";

/** 该记录是否属于「用户手动新建」（而非 Excel 导入的历史值） */
export function isManualEntry(createdAt: Date): boolean {
  // 取 UTC 日期的字符串（与 createdAt 存储一致，不受本地时区影响）
  const d = createdAt.toISOString().slice(0, 10);
  return d > IMPORT_BATCH_DATE;
}